using SeneCare.Application.Properties;
using SeneCare.Application.Requests;
using SeneCare.Application.Subscriptions;
using SeneCare.Domain.Accounts;
using SeneCare.Domain.Common;

namespace SeneCare.Web.ViewModels;

public sealed class PropertyFormModel
{
    public PropertyKind Kind { get; set; } = PropertyKind.House;

    public string? Name { get; set; }

    public Guid? NeighborhoodId { get; set; }

    public string? NeighborhoodLabel { get; set; }

    /// <summary>Text, not double: the map writes « 14.7167 » and French model binding would expect « 14,7167 ».</summary>
    public string? Latitude { get; set; }

    public string? Longitude { get; set; }

    public static double? ParseCoordinate(string? value) =>
        double.TryParse(value, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out var number) ? number : null;

    public string? Landmark { get; set; }

    public string? Details { get; set; }
}

/// <summary>The 3-step report form.</summary>
public sealed class ReportFormModel
{
    public Guid? PropertyId { get; set; }

    public ServiceDomain? Domain { get; set; }

    public string? Description { get; set; }

    public Urgency? Urgency { get; set; }

    /// <summary>Preferred half-days, as « 2026-10-13T08:00:00Z » start times.</summary>
    public List<DateTimeOffset> Slots { get; set; } = [];

    /// <summary>Generated by the phone: an offline replay never creates the request twice.</summary>
    public string? ClientReference { get; set; }
}

public sealed class ReportPageModel
{
    public required IReadOnlyList<PropertySummary> Properties { get; init; }

    public required IReadOnlyList<(DateTimeOffset Start, DateTimeOffset End)> SlotChoices { get; init; }

    public required ReportFormModel Form { get; init; }

    /// <summary>Why the user cannot report yet (no home, subscription to activate), or null.</summary>
    public string? Blocker { get; init; }
}

public sealed class RequestPageModel
{
    public required RequestDetail Detail { get; init; }

    public required IReadOnlyList<TimelineStep> Timeline { get; init; }

    public bool CanSimulate { get; init; }
}

public sealed class ClientHomeModel
{
    public SubscriptionSummary? Subscription { get; init; }

    public RequestSummary? ActiveRequest { get; init; }

    public IReadOnlyList<TimelineStep> ActiveTimeline { get; init; } = [];

    public NeighborhoodProgress? Neighborhood { get; init; }

    public int PropertyCount { get; init; }

    public int RequestCount { get; init; }

    /// <summary>Advice of the month written by SENECARE (null: the built-in seasonal advice).</summary>
    public SeneCare.Domain.Content.PreventiveAdvice? Advice { get; init; }

    /// <summary>The home neighborhood's public page (news, share link).</summary>
    public SeneCare.Application.Neighborhoods.NeighborhoodPage? Community { get; init; }

    public SeneCare.Application.Neighborhoods.ReferralStats? Referral { get; init; }
}

/// <summary>A subscription and, when something is due, the invoice to pay with the Wave link (+ its QR code).</summary>
public sealed record SubscriptionPageItem(SubscriptionSummary Subscription, SeneCare.Application.Payments.InvoiceDue? Due, string? QrSvg);
